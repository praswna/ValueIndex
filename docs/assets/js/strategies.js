export function initStrategies(rootId) {
  const root = document.getElementById(rootId);
  const sorted = [...STRATEGIES].sort((a, b) => b.stars - a.stars);
  root.innerHTML = sorted.map((s, i) => `
    <button class="tile" data-strat="${s.id}">
      <span class="tile-label">${i + 1}. ${s.label}</span>
      <span class="tile-value" style="font-size:1.05rem">${STARS(s.stars)}</span>
      <span class="tile-sub">${s.tag}</span>
    </button>`).join("");

  root.addEventListener("click", (e) => {
    const tile = e.target.closest(".tile");
    if (!tile) return;
    const s = STRATEGIES.find((x) => x.id === tile.dataset.strat);
    openModal(`
      <h2 style="margin:0 0 2px">${s.label}</h2>
      <div style="font-size:1.25rem">${STARS(s.stars)}
        <span class="metric-delta">엣지 원천: ${s.tag}</span></div>
      <p class="caption" style="margin:4px 0 10px"><b>${s.line}</b></p>
      <div class="modal-desc">
        <p><b>무엇인가</b> — ${s.what}</p>
        <p><b>왜 돈이 되(었)나</b> — ${s.why}</p>
        <p><b>개인이 한다면</b> — ${s.how}</p>
        <p><b>대표 사례</b> — ${s.people}</p>
        <p><b>함정</b> — ${s.traps}</p>
      </div>
      <div class="box ${s.stars >= 4 ? "box-good" : s.stars >= 3 ? "box-info" : "box-warn"} note-sm">
        <b>별점 근거</b> — ${s.verdict}</div>
      <p class="caption">별점 = "개인이 실행해서 장기적으로 득 볼 가능성"에 대한 이 앱의
        주관적 평가입니다. 전략 자체의 우열이 아니라 <b>개인의 자리</b>가 기준입니다.</p>`);
  });
}
